/**
 * Counts set bits (1s) using Brian Kernighan's Algorithm.
 *
 * STEP-BY-STEP TRACE (e.g., num = 13, binary 1101):
 * Initial: count = 0, num = 13 (1101)
 *
 * Loop 1:
 *   Step 1: Calculate num - 1  =>  12 (1100)
 *   Step 2: Bitwise AND (&)    =>  13 & 12 = 1101 & 1100 = 12 (1100)
 *   Step 3: Increment count    =>  count = 1
 *
 * Loop 2:
 *   Step 1: Calculate num - 1  =>  11 (1011)
 *   Step 2: Bitwise AND (&)    =>  12 & 11 = 1100 & 1011 = 8 (1000)
 *   Step 3: Increment count    =>  count = 2
 *
 * Loop 3:
 *   Step 1: Calculate num - 1  =>  7 (0111)
 *   Step 2: Bitwise AND (&)    =>  8 & 7 = 1000 & 0111 = 0 (0000)
 *   Step 3: Increment count    =>  count = 3
 *
 * Loop 4: num is 0 -> Loop terminates
 * Result: 3
 */

function countSetBitsOptimal(num) {
  let count = 0;

  // Repeat until all set bits (1s) have been turn to 0
  while (num > 0) {
    // Step 1: `num - 1` flips the lowest set bit to 0 and all trailing 0s to 1s.
    // Step 2: `num & (num - 1)` turns off that lowest set bit in `num`.
    num = num & (num - 1);

    // Step 3: Count that one set bit was successfully removed.
    count++;
  }

  return count;
}


