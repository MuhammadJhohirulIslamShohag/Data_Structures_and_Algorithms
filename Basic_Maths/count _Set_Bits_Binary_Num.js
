/*
  Count Set Bits in a Binary Number

Given a positive integer num, determine the number of set bits (1s) present in the binary representation of the given number, commonly referred to as the Hamming weight.

*/

/**
 * Counts set bits (1s) by simulating manual binary conversion.
 *
 * STEP-BY-STEP TRACE (e.g., num = 13, binary 1101):
 * Initial: count = 0, num = 13
 * Loop 1:  13 % 2 = 1 -> count = 1 | Math.floor(13 / 2) = 6
 * Loop 2:   6 % 2 = 0 -> count = 1 | Math.floor(6 / 2)  = 3
 * Loop 3:   3 % 2 = 1 -> count = 2 | Math.floor(3 / 2)  = 1
 * Loop 4:   1 % 2 = 1 -> count = 3 | Math.floor(1 / 2)  = 0 (Stop)
 * Result:  3
 */

function countSetBitsBruteForce(num) {
  let count = 0;

  // Process the binary representation one bit at a time, right-to-left
  while (num > 0) {
    // Step 1: Check the last bit (remainder of division by 2 is 1 if bit is set)
    count += num % 2;

    // Step 2: Remove the last bit by dividing by 2 and rounding down
    num = Math.floor(num / 2);
  }

  return count;
}

